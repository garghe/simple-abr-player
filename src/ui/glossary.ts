const norm = (s: string) => s.trim().toLowerCase().replace(/\s+/g, ' ');

/** Explanation for a label, or undefined. `context` (e.g. 'scte') is tried first as "context:label". */
export function tipFor(label: string, context?: string): string | undefined {
  const l = norm(label);
  if (!l || l.length > 60) return undefined;
  return (
    (context ? GLOSSARY[`${context}:${l}`] : undefined) ??
    GLOSSARY[l] ??
    GLOSSARY[l.replace(/\s*\(.*\)$/, '')] ??
    GLOSSARY[l.replace(/\s*[×x]?\d+$/, '')] ??
    GLOSSARY[l.replace(/^drm · .*/, 'drm')]
  );
}
